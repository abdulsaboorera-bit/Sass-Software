"use strict";

const mongoose = require("mongoose");
const models = require("../models");
const { DATASETS } = require("./datasets.service");

/**
 * Generic, dependency-free demo seeder.
 *
 * Instead of hand-writing sample data for every one of the ~45 models, this
 * reads each model's schema at runtime (`schema.paths`) and synthesises a few
 * plausible records per module. Values are chosen from the field name and type
 * (emails look like emails, dates look like dates, enums pick a valid member),
 * so demo tenants get a populated dashboard for their industry immediately.
 */

const FIRST = ["Ahmed", "Bilal", "Sara", "Ayesha", "Hamza", "Fatima", "Usman", "Zainab", "Ali", "Hina", "Omar", "Mariam"];
const LAST = ["Khan", "Malik", "Raza", "Iqbal", "Sheikh", "Ahmed", "Butt", "Chaudhry", "Qureshi", "Baig"];
const CITIES = ["Karachi", "Lahore", "Islamabad", "Rawalpindi", "Faisalabad", "Multan"];
const CATEGORIES = ["General", "Standard", "Premium", "Misc", "Operations"];
const SPECIALTIES = ["General", "Cardiology", "Dermatology", "Orthopedics", "Pediatrics"];
const ROLES = ["Manager", "Staff", "Assistant", "Receptionist"];
const SUBJECTS = ["Mathematics", "English", "Science", "Urdu", "Computer"];
const BLOOD = ["O+", "A+", "B+", "AB+", "O-"];

const RESERVED = new Set(["_id", "id", "__v", "tenantId", "createdAt", "updatedAt", "createdBy", "updatedBy"]);

function pick(arr, i) {
  return arr[i % arr.length];
}

function randInt(min, max) {
  return Math.floor(Math.random() * (max - min + 1)) + min;
}

/** Choose a value for one schema path based on its name + type. */
function valueFor(path, schemaType, i) {
  const p = path.toLowerCase();
  const instance = schemaType.instance;

  // Enums always win — returns a valid member.
  if (Array.isArray(schemaType.enumValues) && schemaType.enumValues.length) {
    return schemaType.enumValues[i % schemaType.enumValues.length];
  }

  // Name-driven string values.
  if (instance === "String") {
    if (p.includes("email")) return `demo${i + 1}@example.com`;
    if (p.includes("phone") || p.includes("mobile") || p.includes("whatsapp") || p.includes("contact")) {
      return `0300123${String(4000 + i).slice(-4)}`;
    }
    if (p.includes("cnic") || p === "nic" || p.includes("nationalid")) return `35202-${1000000 + i}-${i % 9 + 1}`;
    if (p.includes("isbn")) return `978-3-16-14841${i % 10}-${i % 10}`;
    if (p.includes("plate")) return `ABC-${100 + i}`;
    if (p.includes("admissionno")) return `ADM-${1000 + i}`;
    if (p.includes("patientno")) return `PAT-${1000 + i}`;
    if (p.includes("customerno")) return `CUS-${1000 + i}`;
    if (p.includes("memberno")) return `MEM-${1000 + i}`;
    if (p.includes("unitno")) return `U-${100 + i}`;
    if (p.includes("invoiceno") || p.includes("invoiceref")) return `INV-${1000 + i}`;
    if (p.includes("code") || p.includes("sku") || p.includes("reference") || p === "ref") return `CODE-${1000 + i}`;
    if (p.includes("guardian")) return `${pick(FIRST, i + 3)} ${pick(LAST, i)}`;
    if (p.includes("gender")) return i % 2 === 0 ? "Male" : "Female";
    if (p.includes("blood")) return pick(BLOOD, i);
    if (p.includes("city")) return pick(CITIES, i);
    if (p.includes("address")) return `${100 + i} Demo Street, ${pick(CITIES, i)}`;
    if (p.includes("specialization") || p.includes("specialty")) return pick(SPECIALTIES, i);
    if (p.includes("subject")) return pick(SUBJECTS, i);
    if (p.includes("role") || p.includes("designation")) return pick(ROLES, i);
    if (p.includes("category") || p.includes("type")) return pick(CATEGORIES, i);
    if (p.includes("status")) return "ACTIVE";
    if (p.includes("time")) return "10:00";
    if (p.includes("url") || p.includes("link") || p.includes("website")) return "https://example.com";
    if (p.includes("author")) return `${pick(FIRST, i)} ${pick(LAST, i + 2)}`;
    if (p.includes("publisher")) return "Demo Press";
    if (p.includes("description") || p.includes("notes") || p.includes("message") || p.includes("reason") || p.includes("diagnosis")) {
      return "Sample record generated by the demo data seeder.";
    }
    if (p.includes("name") || p.includes("title") || p.includes("label")) return `${pick(FIRST, i)} ${pick(LAST, i)}`;
    return `Sample ${i + 1}`;
  }

  if (instance === "Number") {
    if (p.includes("amount") || p.includes("price") || p.includes("fee") || p.includes("salary") || p.includes("cost") || p.includes("total") || p.includes("rent") || p.includes("rate")) {
      return randInt(500, 15000);
    }
    if (p.includes("year")) return 2024;
    if (p.includes("duration")) return 30;
    if (p.includes("quantity") || p.includes("qty") || p.includes("copies") || p.includes("stock") || p.includes("guests") || p.includes("capacity")) {
      return randInt(5, 50);
    }
    if (p.includes("percent") || p.includes("rate")) return 10;
    return randInt(1, 100);
  }

  if (instance === "Date") return new Date();
  if (instance === "Boolean") return true;
  if (instance === "ObjectId") {
    // Random reference for required relations; otherwise leave unset.
    return schemaType.isRequired || schemaType.options && schemaType.options.required
      ? new mongoose.Types.ObjectId()
      : undefined;
  }
  return undefined;
}

/** Build one demo document for a model. */
function buildDoc(Model, i) {
  const doc = {};
  const schema = Model.schema;
  for (const path of Object.keys(schema.paths)) {
    if (RESERVED.has(path) || path.startsWith("__")) continue;
    const schemaType = schema.path(path);
    if (!schemaType || schemaType.instance === "Array" || schemaType.instance === "Mixed") continue;
    const val = valueFor(path, schemaType, i);
    if (val !== undefined) doc[path] = val;
  }
  return doc;
}

/**
 * Seed demo records for every dataset belonging to `industry`.
 * Skips any module that already has data for the tenant (idempotent-ish).
 */
async function seedIndustryDemo(tenantId, industry, { perModule = 4 } = {}) {
  const sealed = [];
  const entries = Object.entries(DATASETS).filter(([, v]) => v.industry === industry);

  for (const [key, entry] of entries) {
    const Model = models[entry.model];
    if (!Model) continue;
    try {
      // eslint-disable-next-line no-await-in-loop
      const existing = await Model.countDocuments({ tenantId });
      if (existing > 0) { sealed.push({ key, created: 0, skipped: "existing" }); continue; }
      const docs = [];
      for (let i = 0; i < perModule; i += 1) docs.push({ ...buildDoc(Model, i), tenantId });
      // eslint-disable-next-line no-await-in-loop
      const inserted = await Model.insertMany(docs, { ordered: false });
      sealed.push({ key, created: inserted.length });
    } catch (err) {
      // Insert partially failed (e.g. a unique index) — report and move on.
      const inserted = err && err.insertedDocs ? err.insertedDocs.length : 0;
      sealed.push({ key, created: inserted, error: err.message });
    }
  }

  return sealed;
}

module.exports = { seedIndustryDemo };
